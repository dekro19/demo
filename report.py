"""Глава 2. Отчёт свидетеля и журнал событий."""

from rounds import Case, Chapter, Round


def mask_codes(regex, source):
    return regex.sub("[СКРЫТО]", source)


def split_log(regex, source):
    return regex.split(source)


CHAPTER = Chapter(
    "Архивный журнал",
    (
        Round(
            title="Закрытые данные",
            task=(
                "Чтобы передать черновик следователю, замените коды свидетелей "
                "на [СКРЫТО] через re.sub. Код — WK- и четыре цифры ASCII. "
                "Регистр важен. С каждой стороны кода допустима граница строки "
                "или несловесный символ (\\W в Python). Маскируйте только код "
                "целиком, сохраняя остальной текст без изменений."
            ),
            operation=mask_codes,
            public=(
                Case("Свидетель (WK-0042), дубль WK-9999.", "Свидетель ([СКРЫТО]), дубль [СКРЫТО]."),
                Case("Номер WK-12345 сохранён.", "Номер WK-12345 сохранён."),
            ),
            hidden=(
                Case("WK-0000/WK-0000\nWK-1200", "[СКРЫТО]/[СКРЫТО]\n[СКРЫТО]"),
                Case("XWK-1234 WK-1234_ яWK-1234 WK-1234я", "XWK-1234 WK-1234_ яWK-1234 WK-1234я"),
                Case("wk-7777 WK-١٢٣٤ WK-001 [WK-8888]", "wk-7777 WK-١٢٣٤ WK-001 [[СКРЫТО]]"),
                Case("", ""),
            ),
            hint="Задайте границы через \\b, чтобы re.sub сохранил скобки и другие знаки вокруг кода.",
            clue="В отчёте указан резервный журнал, восстановленный из склейки событий.",
        ),
        Round(
            title="Последовательность событий",
            task=(
                "Разделите журнал через re.split. Разделитель — один символ | "
                "или ; либо пара знаков >>. Включите в разделитель все "
                "прилегающие обычные пробелы и табуляции с обеих сторон. "
                "Одиночные >, запятые, дефисы, переводы строки и пробелы внутри "
                "записи сохраняются. Соседние разделители, а также разделители "
                "в начале или конце дают пустые записи. Верните только записи."
            ),
            operation=split_log,
            public=(
                Case("пропуск | вскрыт шкаф >> папка найдена", ["пропуск", "вскрыт шкаф", "папка найдена"]),
                Case("метка > 7;сейф, закрыт", ["метка > 7", "сейф, закрыт"]),
            ),
            hidden=(
                Case("\tA\t|\tB ; C>>D", ["\tA", "B", "C", "D"]),
                Case("|A; \t>>B|", ["", "A", "", "B", ""]),
                Case("A\n\t| \tB-1", ["A\n", "B-1"]),
                Case("  одна запись  ", ["  одна запись  "]),
                Case("A>>>B", ["A", ">B"]),
                Case("", [""]),
            ),
            hint="Сгруппируйте варианты через (?:...). Обычная группа попадёт в результат split.",
            clue="Журнал подтвердил перемещение дела в резервный сейф после сбоя замка BOX-07.",
        ),
    ),
)
